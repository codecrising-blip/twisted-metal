#!/usr/bin/env python3
"""Writes scripts/fx/sound_peaks.gd: for every sound in audio/sfx, the time (s) of its loudest 20 ms.
GameFeel uses it to line the peak of a sound up with the frame it belongs to (juice guide, section 6).
Run after adding or replacing sounds:  python3 tests/sound_peaks.py"""
import math, os, struct, subprocess

SFX = os.path.join(os.path.dirname(__file__), "..", "audio", "sfx")


def peak_time(path, step=0.02, rate=22050):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", str(rate), "-f", "s16le", "-"],
                         capture_output=True, check=True).stdout
    s = struct.unpack("<%dh" % (len(raw) // 2), raw)
    w = int(rate * step)
    best, at = -1.0, 0
    for i in range(0, len(s), w):
        seg = s[i:i + w]
        e = math.sqrt(sum(x * x for x in seg) / max(1, len(seg)))
        if e > best:
            best, at = e, i
    return round(at / rate, 3)


peaks = {}
for name in sorted(os.listdir(SFX)):
    if name.endswith((".ogg", ".wav", ".mp3")):
        peaks[os.path.splitext(name)[0]] = peak_time(os.path.join(SFX, name))
out = os.path.join(os.path.dirname(__file__), "..", "scripts", "fx", "sound_peaks.gd")
with open(out, "w") as f:
    f.write("class_name SoundPeaks\nextends RefCounted\n")
    f.write("## GENERATED by tests/sound_peaks.py: the time (s) of each sound's loudest moment. Do not edit by hand.\n\n")
    f.write("const PEAKS := {\n")
    for k, v in peaks.items():
        f.write('\t"%s": %s,\n' % (k, v))
    f.write("}\n")
print("%d sounds" % len(peaks))
